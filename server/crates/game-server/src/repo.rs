//! Persistence of worlds (plan 02 §3.2 `WorldRepository`, §7): a snapshot (a checkpoint: the whole
//! `SaveFile` — world, tempo schedule, every command since the start — plus the step state) and a
//! log of what happened after it. Restoring a world continues the checkpoint with the log tail; the
//! result equals the replay of the whole command log from the scenario's start (tested), which stays
//! the fallback.
//!
//! Adapters: files under `DATA_DIR/worlds/<world>/` (`world.json`, `log.jsonl`) and PostgreSQL
//! (`world_snapshots`, `world_log`; `storage.rs`, R-26). Either is written by one I/O thread fed
//! through a channel, so a world's loop never waits for the disk (rule from `init.md`).

use std::fs::{self, OpenOptions};
use std::io::{BufRead, BufReader, Write};
use std::path::{Path, PathBuf};
use std::sync::mpsc;

use serde::{Deserialize, Serialize};

use game_core::models::command::Command;
use game_core::sim::simulation::SimState;
use game_session::{SaveFile, TempoChange};

use crate::accounts::write_atomic;

/// What `world.json` holds.
#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct StoredWorld {
    /// Wall clock of the snapshot [Unix ms]; a sleeping world catches up from here.
    pub saved_at_ms: f64,
    pub save: SaveFile,
    /// Step state outside the world (`Checkpoint`): with it the snapshot continues exactly and only
    /// the log tail is replayed. Missing in snapshots written before it existed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sim: Option<SimState>,
    /// The galaxy's season the world belongs to (S3); a world of an older season starts anew.
    /// Missing in snapshots written before seasons: the season running.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub season: Option<u32>,
}

/// One line of `log.jsonl`: what changed after the snapshot.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(untagged)]
pub enum LogEntry {
    Command { step: u64, command: Command },
    Tempo { step: u64, tempo: f64 },
}

pub trait WorldRepository: Send + 'static {
    fn load(&self, world: &str) -> std::io::Result<Option<(StoredWorld, Vec<LogEntry>)>>;
    /// New snapshot; the log restarts empty after it.
    fn write_snapshot(&self, world: &str, stored: &StoredWorld) -> std::io::Result<()>;
    fn append(&self, world: &str, entry: &LogEntry) -> std::io::Result<()>;
}

impl<T: WorldRepository + ?Sized> WorldRepository for Box<T> {
    fn load(&self, world: &str) -> std::io::Result<Option<(StoredWorld, Vec<LogEntry>)>> {
        (**self).load(world)
    }

    fn write_snapshot(&self, world: &str, stored: &StoredWorld) -> std::io::Result<()> {
        (**self).write_snapshot(world, stored)
    }

    fn append(&self, world: &str, entry: &LogEntry) -> std::io::Result<()> {
        (**self).append(world, entry)
    }
}

pub struct FileRepository {
    dir: PathBuf,
}

impl FileRepository {
    pub fn new(dir: impl Into<PathBuf>) -> FileRepository {
        FileRepository { dir: dir.into() }
    }

    fn world_dir(&self, world: &str) -> PathBuf {
        // world ids are generated by the server ("acc-12"); keep the name safe anyway
        let safe: String = world.chars().map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '_' }).collect();
        self.dir.join(safe)
    }
}

impl WorldRepository for FileRepository {
    fn load(&self, world: &str) -> std::io::Result<Option<(StoredWorld, Vec<LogEntry>)>> {
        let dir = self.world_dir(world);
        let text = match fs::read_to_string(dir.join("world.json")) {
            Ok(t) => t,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(e),
        };
        let stored: StoredWorld = serde_json::from_str(&text).map_err(std::io::Error::other)?;
        let mut log = Vec::new();
        if let Ok(f) = fs::File::open(dir.join("log.jsonl")) {
            for line in BufReader::new(f).lines() {
                let line = line?;
                if line.trim().is_empty() {
                    continue;
                }
                // a torn last line (crash while writing) ends the log
                match serde_json::from_str::<LogEntry>(&line) {
                    Ok(e) => log.push(e),
                    Err(_) => break,
                }
            }
        }
        Ok(Some((stored, log)))
    }

    fn write_snapshot(&self, world: &str, stored: &StoredWorld) -> std::io::Result<()> {
        let dir = self.world_dir(world);
        fs::create_dir_all(&dir)?;
        let bytes = serde_json::to_vec(stored).map_err(std::io::Error::other)?;
        write_atomic(&dir.join("world.json"), &bytes)?;
        fs::write(dir.join("log.jsonl"), b"")
    }

    fn append(&self, world: &str, entry: &LogEntry) -> std::io::Result<()> {
        let dir = self.world_dir(world);
        fs::create_dir_all(&dir)?;
        let mut f = OpenOptions::new().create(true).append(true).open(dir.join("log.jsonl"))?;
        let mut line = serde_json::to_vec(entry).map_err(std::io::Error::other)?;
        line.push(b'\n');
        f.write_all(&line)
    }
}

/// The save file the snapshot and the log add up to: commands and tempo changes appended, the step
/// moved to the last logged one.
pub fn combine(stored: &StoredWorld, log: &[LogEntry]) -> SaveFile {
    let mut save = stored.save.clone();
    for e in log {
        match e {
            LogEntry::Command { step, command } => {
                save.commands.push(game_session::RecordedCommand { step: *step, command: command.clone() });
                save.step = save.step.max(*step);
            }
            LogEntry::Tempo { step, tempo } => {
                match save.tempos.last_mut() {
                    Some(last) if last.step == *step => last.tempo = *tempo,
                    _ => save.tempos.push(TempoChange { step: *step, tempo: *tempo }),
                }
                save.step = save.step.max(*step);
            }
        }
    }
    save
}

pub enum RepoOp {
    Snapshot {
        world: String,
        stored: Box<StoredWorld>,
    },
    Append {
        world: String,
        entry: LogEntry,
    },
    /// Answers when every operation sent before it is done (shutdown, tests).
    Flush(std::sync::mpsc::Sender<()>),
    /// Runs once every operation sent before it is written: what other services hear of a command
    /// (a shipment to a hub, a delivery taken) follows the command in the log, so a crash between
    /// the two never leaves the galaxy ahead of the world.
    Then(Box<dyn FnOnce() + Send>),
}

/// Sender side of the I/O thread. Cloned into every world.
#[derive(Clone)]
pub struct Persister {
    tx: mpsc::Sender<RepoOp>,
}

impl Persister {
    pub fn spawn<R: WorldRepository>(repo: R) -> Persister {
        let (tx, rx) = mpsc::channel::<RepoOp>();
        std::thread::Builder::new()
            .name("world-io".into())
            .spawn(move || {
                for op in rx {
                    let result = match op {
                        RepoOp::Snapshot { world, stored } => repo.write_snapshot(&world, &stored),
                        RepoOp::Append { world, entry } => repo.append(&world, &entry),
                        RepoOp::Flush(done) => {
                            let _ = done.send(());
                            Ok(())
                        }
                        RepoOp::Then(f) => {
                            f();
                            Ok(())
                        }
                    };
                    if let Err(e) = result {
                        eprintln!("world-io: {e}");
                    }
                }
            })
            .expect("spawn world-io thread");
        Persister { tx }
    }

    pub fn send(&self, op: RepoOp) {
        let _ = self.tx.send(op);
    }

    /// Blocks until the queue before this call is written.
    pub fn flush(&self) {
        let (done, wait) = mpsc::channel();
        self.send(RepoOp::Flush(done));
        let _ = wait.recv();
    }
}

pub fn data_worlds_dir(data_dir: &Path) -> PathBuf {
    data_dir.join("worlds")
}
